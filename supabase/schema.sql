-- AgriWise Connect: private field-analysis database
-- Run this once in Supabase SQL Editor for the project owned by you.

create table if not exists public.field_analyses (
  id bigint generated by default as identity primary key,
  module text not null check (module in (
    'crop-prediction',
    'pest-detection',
    'fertilizer-prediction',
    'nutrient-deficiency',
    'smart-irrigation',
    'expert-advisor',
    'farm-market-planner'
  )),
  title text not null,
  input_data jsonb not null default '{}'::jsonb,
  result_data jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

alter table public.field_analyses enable row level security;

-- Demo/hackathon mode: the public client may create analysis records.
-- SELECT is intentionally disabled, so the database is not a public history API.
drop policy if exists "allow_analysis_insert" on public.field_analyses;
create policy "allow_analysis_insert"
on public.field_analyses
for insert
to anon, authenticated
with check (true);

-- Owner-controlled read access. If you later add Supabase Auth, replace this
-- with an authenticated-owner policy tied to your user id.
drop policy if exists "allow_analysis_select_authenticated" on public.field_analyses;
create policy "allow_analysis_select_authenticated"
on public.field_analyses
for select
to authenticated
using (auth.uid() is not null);

create index if not exists field_analyses_created_at_idx
on public.field_analyses (created_at desc);
